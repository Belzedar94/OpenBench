# The first table grows by the three main replies to 1.Nf3, and every position
# the opening catalogue names (atomicdb/data/atomic_openings_v1.json) is
# followed the same way (atomicdb.roots): 365 keys instead of 21.  No new
# table; the trigger of 0050 gets a new WHEN and the new rows are seeded.
#
# WHY THE WHEN CHANGES FORM.  0050 asked ``NEW.key IN (<21 constants>)``, and
# a trigger's WHEN is not planned like a query.  PostgreSQL rebuilds it from
# pg_trigger.tgqual for every UPDATE statement that sets one of the three
# columns (TriggerEnabled: stringToNode, then ExecPrepareQual, whose
# expression_planner only folds constants), so its size is paid once per
# statement; and nothing turns an IN list into a hash lookup there (only the
# query planner does that), so its length is paid once per updated row.
# Measured on PostgreSQL 16.15 with a 200k-row stand-in for atomicdb_position
# (same key shape, foreign keys pointing at it), 20k one-row UPDATEs and
# 200k-row UPDATEs per form:
#
#     WHEN form                          tgqual    per statement  per changed row
#     IN (21 keys), 0050                   9.7 kB        +40 us       +0.5 us
#     IN (365 keys)                        132 kB       +535 us       +6-7 us
#     jsonb of 365 keys in the WHEN         90 kB       +430 us          ~0
#     jsonb of 12-char key prefixes         30 kB       +143 us       +0.5 us
#     changed AND watched-key function     1.9 kB       +7.5 us       +0.6 us
#
# The last one is what this installs.  The WHEN first asks whether one of the
# three values really changed (a rewrite of the same values never reaches the
# function), then calls ``atomicdb_watched_key(NEW.key)``: a plpgsql function
# whose body looks the key up in a constant jsonb object, a binary search of
# about nine comparisons.  plpgsql compiles that body once per session, so the
# list is not re-read per statement; a SQL-language function would be inlined
# into the WHEN and its body parsed again every statement, which is why it is
# plpgsql.  Production takes about a thousand row updates a minute: even if
# every one were its own statement, that is under 10 ms of CPU a minute, where
# the 365-key IN list would cost about half a second.
#
# CHANGING THE LIST LATER.  A new catalogue, or another reply to follow, needs
# a new migration, and it only has to CREATE OR REPLACE the function (plus seed
# the new keys): replacing a function takes no lock on atomicdb_position.
# atomicdb/test_root_extremes.py holds the list below equal to what
# ``roots.watched_keys()`` computes from the move generator and the catalogue,
# so changing either without a migration fails the tests.
#
# PostgreSQL only, as in 0050; the seeding runs on both engines and never
# touches a row that already exists, so the 21 rows of 0050 keep their history.

